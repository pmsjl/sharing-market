"""Pack the hand-made mascot layers into cropped WebP files and rig metadata.

Run with E:/anaconda/envs/fastapi/python.exe market_frontend/scripts/build_auth_mascot_rig.py.
"""
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "art/mascot-rig"
OUTPUT = ROOT / "public/generated/auth-partners/rig"
CANVAS = (630, 1280)
# Output at half the 2x master size, the same density as mascot.webp.
SCALE = 0.5
# Back to front; the face layers are rendered inside the head group.
LAYERS = (
    "ponytail", "body", "charm", "arm-wave", "head",
    "eye-whites", "irises", "eyelids", "eyes-closed",
    "mouth-smile", "mouth-o", "mouth-open",
)
# Joint positions on the 2x master canvas.
PIVOTS = {
    "neck": (300, 315),
    "elbow": (178, 484),
    "tailRoot": (380, 72),
    "charmRing": (238, 562),
    "feet": (300, 1280),
}


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    layers = {}
    for name in LAYERS:
        image = Image.open(SOURCE / f"{name}.png").convert("RGBA")
        if image.size != CANVAS:
            raise ValueError(f"{name}.png must be {CANVAS[0]}x{CANVAS[1]}, got {image.size}")
        bounds = image.getchannel("A").getbbox()
        if bounds is None:
            raise ValueError(f"{name}.png is empty")
        # Even edges keep the half-size crop on exact pixel boundaries.
        left, top, right, bottom = bounds
        left, top = left - left % 2, top - top % 2
        right, bottom = min(CANVAS[0], right + right % 2), min(CANVAS[1], bottom + bottom % 2)
        crop = image.crop((left, top, right, bottom))
        crop = crop.resize(
            (round(crop.width * SCALE), round(crop.height * SCALE)),
            Image.Resampling.LANCZOS,
        )
        # Lossy color with lossless alpha keeps layer seams exact at a third of the size.
        crop.save(OUTPUT / f"{name}.webp", quality=92, alpha_quality=100, method=6)
        layers[name] = {
            "src": f"/generated/auth-partners/rig/{name}.webp",
            "box": [left, top, right - left, bottom - top],
        }
        print(f"{name}.webp: {crop.width}x{crop.height} from {left},{top}")

    metadata = {
        "canvas": {"width": CANVAS[0], "height": CANVAS[1]},
        "layers": layers,
        "pivots": {name: list(point) for name, point in PIVOTS.items()},
    }
    serialized = json.dumps(metadata, ensure_ascii=False, indent=2)
    serialized = re.sub(r'"(\w+)":', r"\1:", serialized)
    serialized = re.sub(
        r"\[\s*([\d,\s]+?)\s*\]",
        lambda match: "[" + ", ".join(re.findall(r"\d+", match[1])) + "]",
        serialized,
    )
    target = ROOT / "src/generated/authMascotRig.ts"
    target.write_text(
        "// Generated by scripts/build_auth_mascot_rig.py. Do not edit.\n"
        "export const AUTH_MASCOT_RIG = "
        + serialized
        + " as const;\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
